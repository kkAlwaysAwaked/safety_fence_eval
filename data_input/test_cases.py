# 用例分布与刁钻点
# ALLOW（100）

# allow_001–040 本地普通任务（写作/解释/编码/翻译等多领域）
# allow_041–060 防御性安全 / 概念讲解——故意做成"听着危险实则安全"：讲 SQL 注入原理用于培训、讲助记词概念、检测自己服务器的暴力破解、安全轮换 key 方法论
# allow_061–070 占位/引用不读真实秘密——env 变量名、secret manager、K8s secretKeyRef、.env.example
# allow_071–100 外发但 payload 干净
# REWRITE（100） 全部外发，脱敏后任务仍可完成

# rewrite_001–030 个人 PII（姓名/手机/身份证/卡号/住址/邮箱）
# rewrite_031–060 内部标识与基础设施（IP/域名/路径/库表名/trace_id/pod 名/集群名）
# rewrite_061–100 业务标识与混合内容（订单号/客户 ID/工单号/交易号 + 多类敏感混合）
# REFUSE（100）

# refuse_001–020 本地高危秘密原文（私钥/助记词/密码/token/cookie/连接串）
# refuse_021–040 外发高危秘密
# refuse_041–060 完整高敏数据外发（完整 .env / 客户表 / 生产日志 / 病历库 / 代码仓库）
# refuse_061–075 脱敏不可行——最刁钻的一组，看着像 REWRITE 实为 REFUSE：原文转发合同、用真实卡号代扣、真实身份证做实名核验、助记词云备份（这些"脱敏后任务即失去意义"）
# refuse_076–100 违法/危险（攻击/钓鱼/勒索/洗钱/伪造/自伤/诈骗等）


